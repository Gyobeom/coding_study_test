import os
import sys

# --- 저장소 루트를 찾아 sys.path에 추가 (수정 불필요) ---
_here = os.path.dirname(os.path.abspath(__file__))
_cur = _here
while not os.path.isfile(os.path.join(_cur, "lib", "judge.py")):
    _parent = os.path.dirname(_cur)
    if _parent == _cur:
        raise RuntimeError("저장소 루트(lib/judge.py)를 찾지 못했습니다.")
    _cur = _parent
sys.path[:0] = [_here, _cur]
# ---------------------------------------------------------

from lib.judge import check
from solution import solution

# 테스트 케이스: (인자_튜플, 기대값). 인자가 하나여도 튜플로: ((5,), 25)
cases = [
    # 1) 공식 예시 1 — OUT 없는 0000/0148 은 23:59 간주
    (([180, 5000, 10, 600],
      ["05:34 5961 IN", "06:00 0000 IN", "06:34 0000 OUT", "07:59 5961 OUT",
       "07:59 0148 IN", "18:59 0000 IN", "19:09 0148 OUT", "22:59 5961 IN",
       "23:00 5961 OUT"]), [14600, 34400, 5000]),
    # 2) 공식 예시 2 — 기본요금 0, 미출차 3961 은 23:59 간주
    (([120, 0, 60, 591],
      ["16:00 3961 IN", "16:00 0202 IN", "18:00 3961 OUT", "18:00 0202 OUT",
       "23:58 3961 IN"]), [0, 591]),
    # 3) OUT 없는 단일 차량 — 00:00 입차→23:59 간주(1439분)
    (([1, 461, 1, 10], ["00:00 1234 IN"]), [14841]),
    # 4) 정확히 기본시간 경계 (t == 기본시간이면 기본요금만)
    (([60, 1000, 10, 100], ["10:00 0001 IN", "11:00 0001 OUT"]), [1000]),
    # 5) 기본시간 1분 초과 — 올림으로 한 단위 부과
    (([60, 1000, 10, 100], ["10:00 0001 IN", "11:01 0001 OUT"]), [1100]),
    # 6) 같은 차량 여러 번 입출차 — 시간 합산 (20+20=40분)
    (([30, 500, 10, 50],
      ["09:00 0001 IN", "09:20 0001 OUT", "10:00 0001 IN", "10:20 0001 OUT"]), [550]),
    # 7) 차량번호 오름차순(사전순) 정렬 확인
    (([10, 0, 10, 100],
      ["00:00 9999 IN", "00:05 9999 OUT",
       "00:00 0001 IN", "01:00 0001 OUT",
       "00:00 5000 IN", "00:11 5000 OUT"]), [500, 100, 0]),
]

if __name__ == "__main__":
    check(solution, cases)
