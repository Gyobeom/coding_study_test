    # 2) 예시 2 — 일수 [5,10,1,1,20,1]. 앞이 끝날 때 대기 기능이 함께 묶임
    (([95, 90, 99, 99, 80, 99], [1, 1, 1, 1, 1, 1]), [1, 3, 2]),
    # 3) 최소 규모 — 기능 1개
    (([50], [10]), [1]),
    # 4) 앞이 가장 오래 걸림 — 전부 한 날에 배포
    (([10, 99, 99], [1, 100, 100]), [3]),
    # 5) 각자 따로 배포 — 뒤로 갈수록 늦게 끝남
    (([90, 80, 70], [10, 1, 1]), [1, 1, 1]),
